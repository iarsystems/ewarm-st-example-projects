/* All bmp assets are present here after init_assets() call. */
BitmapColorType_t bmp_assets[BMP_ASSET_COUNT];

const uint16_t* get_bmp_dat_asset(uint8_t asset)
{
	if ((bmp_asset_t)asset < BMP_ASSET_COUNT) {
		switch((bmp_asset_t)asset) {
		case AIR: return air_dat;
		case ROCK: return rock_dat;
		case PLAYER: return player_dat;
		case BOX: return box_dat;
		case GOAL: return goal_dat;
		case OTHER: return other_dat;
		}
	}
	return NULL;
}

/*******************************************************************************
 ** Function Name : init_assets
 ** Parameters    : none
 ** Returns       : none
 **
 ** Description   : Initializes all assets
 ******************************************************************************/
void init_assets()
{
	for (uint8_t i = 0; i < BMP_ASSET_COUNT; i++) {
		if ((bmp_asset_t)i < BMP_ASSET_COUNT) {
			bmp_assets[i].H_Size = 9;
			bmp_assets[i].V_Size = 9;
			bmp_assets[i].BitsPP = 12;
			bmp_assets[i].BytesPP = 2;
			bmp_assets[i].pPicStream = (uint32_t *)get_bmp_dat_asset(i);
		}
	}
}

/*******************************************************************************
 ** Function Name : get_bmp_asset
 ** Parameters    : asset - What bmp asset to fetch.
 ** Returns       : NULL if asset was not found, otherwise the asset that was
 **                 found.
 **
 ** Description   : Checks if asset exists and returns is.
 ******************************************************************************/
BitmapColorType_t * get_bmp_asset(bmp_asset_t asset)
{
	if (asset < BMP_ASSET_COUNT) {
		return &(bmp_assets[asset]);
	}
	return NULL;
}
